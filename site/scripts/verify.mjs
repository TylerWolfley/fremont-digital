// Multi-page publication and content-routing regressions.
import assert from 'node:assert/strict';
import { readFile, access } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { homePage } from '../src/pages/home.mjs';
import { servicePage } from '../src/pages/service.mjs';
import { contactPage } from '../src/pages/contact.mjs';
import { sitePages } from '../src/data/pages.mjs';
import { business } from '../src/data/business.mjs';
import { serviceGroups } from '../src/data/services.mjs';
import { publicationConfig } from '../src/config/publication.mjs';
import { contactConfig } from '../src/config/contact.mjs';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const render = (page, config) => page.id === 'home' ? homePage(config) : page.id === 'contact' ? contactPage(config) : servicePage(page.id, config);
const titles = new Set();
let serviceCount = 0;
for (const page of sitePages) {
  const html = await readFile(resolve(root, 'dist', '.' + page.path, 'index.html'), 'utf8');
  assert.equal(html, render(page), `Rebuild ${page.path} before checking.`);
  assert.equal((html.match(/<h1\b/g) || []).length, 1, page.path);
  assert.match(html, /name="robots" content="noindex, nofollow"/);
  assert(!html.includes('rel="canonical"') && !html.includes('Colorado'));
  const ids = [...html.matchAll(/\bid="([^"]+)"/g)].map(match => match[1]);
  assert.equal(ids.length, new Set(ids).size, page.path);
  for (const match of html.matchAll(/href="#([^"]+)"/g)) assert(ids.includes(match[1]));
  for (const match of html.matchAll(/(?:src|href)="(\/[^"#]*)"/g)) {
    const path = new URL(match[1].replaceAll('&amp;', '&'), 'https://example.invalid').pathname;
    await access(resolve(root, 'dist', '.' + path, path.endsWith('/') ? 'index.html' : ''));
  }
  assert(html.includes('href="tel:+13073494694"') && html.includes(business.facebookUrl));
  serviceCount += (html.match(/class="service-detail"/g) || []).length;
  const release = render(page, { indexable: true, siteUrl: 'https://example.invalid/' });
  assert(release.includes(`rel="canonical" href="https://example.invalid${page.path}"`));
  titles.add(release.match(/<title>(.*?)<\/title>/)[1]);
  assert.equal(release.includes('class="past-work"'), page.id === 'websites');
}
assert.equal(titles.size, sitePages.length, 'Each page needs its own search title.');
assert.equal(serviceCount, serviceGroups.flatMap(group => group.services).length);
const home = homePage();
assert(!home.includes('data-category-tabs') && !home.includes('data-inquiry-form'));
assert.equal((home.match(/class="service-story"/g) || []).length, 2);
assert(!home.includes('All of Fremont County') && !home.includes('Less tech trouble.'));
const contact = contactPage();
assert.match(contact, /data-inquiry-form data-endpoint=""/);
assert(contact.includes('Preview:'));
const connected = contactPage(contactConfig({ endpoint: 'https://formspree.io/f/testonly' }));
assert(connected.includes('data-endpoint="https://formspree.io/f/testonly"') && connected.includes('data-submit>Send request'));
assert(!connected.includes('Preview:'));
assert.equal(business.location, 'Fremont County, Wyoming');
assert.equal(business.phoneE164, '+13073494694');
assert(contact.includes('arranged device drop-off'));
assert(!home.includes('Phone resale') && !home.includes('data-search-form'));
assert.throws(() => publicationConfig({ release: true }), /SITE_URL/);
for (const siteUrl of ['http://example.invalid', 'https://example.invalid/subpath', 'https://example.invalid/?x=1', 'https://name:password@example.invalid']) assert.throws(() => publicationConfig({ release: true, siteUrl }));
for (const endpoint of ['http://example.invalid/api/inquiry', 'https://example.invalid/?x=1', 'https://a:b@example.invalid/api/inquiry', 'https://example.invalid/elsewhere', 'https://formspree.io.evil.invalid/f/testonly', 'https://formspree.io/f/', 'https://formspree.io/f/testonly?x=1']) assert.throws(() => contactConfig({ endpoint }));
const release = homePage(publicationConfig({ release: true, siteUrl: 'https://example.invalid' }));
const organization = JSON.parse(release.match(/<script type="application\/ld\+json">([\s\S]+?)<\/script>/)[1]);
assert.equal(organization.areaServed.name, business.location);
assert.equal(organization.email, business.email);
assert(!('address' in organization));
assert.deepEqual(organization.sameAs, [business.facebookUrl]);
assert.match(await readFile(resolve(root, 'dist/robots.txt'), 'utf8'), /Disallow: \/\n/);
assert.match(await readFile(resolve(root, 'dist/404.html'), 'utf8'), /Page not found/);
assert.match(homePage({ headerOnly: true, indexable: true }), /name="robots" content="noindex, nofollow"/);
console.log('Passed: six page outputs, unique metadata, internal destinations, service placement, priorities, contact configuration, assets, and publication guards.');
