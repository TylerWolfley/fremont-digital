// Exercise the public demo as a visitor. No external transport is permitted.
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { readFile } from 'node:fs/promises';
import { servicePage } from '../src/pages/service.mjs';
import { contactPage } from '../src/pages/contact.mjs';
const require = createRequire(import.meta.url);
const arg = process.argv.indexOf('--jsdom-module');
const { JSDOM } = require(arg < 0 ? 'jsdom' : process.argv[arg + 1]);
const dom = new JSDOM(servicePage('automation'), { url: 'https://example.invalid/automation/', runScripts: 'outside-only' });
const w = dom.window, d = w.document;
w.fetch = () => { throw new Error('The demo must not send data'); };
w.eval(await readFile(new URL('../src/scripts/automation-demo.js', import.meta.url), 'utf8'));
const field = name => d.querySelector(`[data-demo-${name}]`);
assert(!d.querySelector('[data-automation-demo]').hidden);
assert(field('complete').disabled);
field('run').click();
assert.equal(field('name').textContent, 'Alex Morgan');
assert.match(field('task').textContent, /Alex/);
assert(!field('complete').disabled);
field('complete').click();
assert.equal(field('record-status').textContent, 'Follow-up complete');
field('run').click();
assert(!field('complete').checked, 'Re-running must create an open task, not retain the old completion.');
field('request').value = 'booking';
field('request').dispatchEvent(new w.Event('change', { bubbles: true }));
assert.equal(field('name').textContent, 'Ready for an inquiry');
assert(field('complete').disabled);
field('run').click();
assert.equal(field('name').textContent, 'Jordan Lee');
assert.match(field('task-detail').textContent, /Nothing has been booked automatically/);
field('reset').click();
assert.equal(field('task').textContent, 'No task yet');
assert.equal(d.activeElement, field('run'));
assert(!d.body.textContent.includes('Office setup & Wi-Fi'), 'General IT should not dilute the automation offer.');
// Older shared links for moved tech services must still select the intended work.
const legacy = new JSDOM(contactPage(), { url: 'https://example.invalid/contact/?category=business-tech&service=office-networking', runScripts: 'outside-only' });
legacy.window.HTMLElement.prototype.scrollIntoView = function() {};
for (const name of ['inquiry-tools.js', 'home.js']) legacy.window.eval(await readFile(new URL(`../src/scripts/${name}`, import.meta.url), 'utf8'));
const form = legacy.window.document.querySelector('form');
assert.equal(form.elements.category.value, 'repairs-tech');
assert.equal(form.elements.service.value, 'office-networking');
assert(!legacy.window.document.querySelector('[data-repair-arrangement]').hidden);
console.log('Passed: local demo record/task creation, completion, scenario changes, repeat/reset behavior, focus, IT separation, and legacy inquiry migration. No external requests.');
